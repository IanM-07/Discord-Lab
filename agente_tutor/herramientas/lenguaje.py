def lenguaje_programacion():
    return (
        "Un lenguaje de programación es un lenguaje diseñado para escribir instrucciones "
        "que una computadora puede interpretar o traducir para realizar una tarea. "
        "Cada lenguaje tiene sus propias reglas de escritura, llamadas sintaxis, que deben "
        "seguirse para que el programa funcione correctamente."
    )


def alto_nivel():
    return (
        "Un lenguaje de alto nivel utiliza una sintaxis más parecida al lenguaje humano, "
        "por lo que resulta más fácil de aprender y programar. No depende directamente del "
        "hardware de la computadora y normalmente necesita un compilador o un intérprete "
        "para poder ejecutarse."
    )


def bajo_nivel():
    return (
        "Un lenguaje de bajo nivel trabaja muy cerca del lenguaje máquina, por lo que permite "
        "un mayor control sobre el hardware. Aunque es más rápido y eficiente, también es "
        "más difícil de escribir y comprender que un lenguaje de alto nivel."
    )


def compilacion_interpretacion():
    return (
        "La compilación y la interpretación son dos formas de traducir un programa para que "
        "la computadora pueda ejecutarlo. La compilación traduce todo el código antes de "
        "ejecutarlo, mientras que la interpretación traduce y ejecuta el programa línea por línea."
    )


def compilador():
    return (
        "Un compilador es un programa que traduce todo el código fuente a lenguaje máquina "
        "antes de ejecutar el programa. Si encuentra errores de sintaxis, los muestra antes "
        "de generar el programa ejecutable."
    )


def interprete():
    return (
        "Un intérprete es un programa que traduce y ejecuta el código fuente línea por línea. "
        "A diferencia del compilador, no traduce todo el programa de una sola vez, por lo que "
        "los errores se detectan conforme se va ejecutando el código."
    )