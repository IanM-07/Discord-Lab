def procedimientos():
    return (
        "Un procedimiento es un conjunto de instrucciones agrupadas para realizar una tarea "
        "específica dentro de un programa. Generalmente se ejecuta cuando es llamado y su "
        "objetivo principal es organizar el código y evitar repetir instrucciones."
    )


def funciones():
    return (
        "Una función es un bloque de código diseñado para realizar una tarea específica. "
        "Puede recibir datos mediante parámetros, procesarlos y devolver un resultado. "
        "Las funciones ayudan a organizar el programa y facilitan la reutilización del código."
    )


def diferencias_funciones():
    return (
        "La principal diferencia entre un procedimiento y una función es que una función "
        "devuelve un resultado después de ejecutarse, mientras que un procedimiento realiza "
        "una tarea específica sin necesidad de regresar un valor."
    )


def invocacion():
    return (
        "La invocación consiste en llamar o ejecutar una función o procedimiento desde otra "
        "parte del programa. Cuando se invoca, el programa transfiere el control a esa función "
        "para ejecutar las instrucciones que contiene."
    )


def parametros():
    return (
        "Los parámetros son datos que se envían a una función o procedimiento para que pueda "
        "trabajar con ellos. Permiten que una misma función pueda utilizarse con diferentes valores."
    )


def parametros_entrada():
    return (
        "Los parámetros de entrada son los valores que recibe una función al momento de ser "
        "llamada. Estos datos son utilizados por la función para realizar alguna operación."
    )


def parametros_salida():
    return (
        "Los parámetros de salida son los datos que una función devuelve después de ejecutar "
        "sus instrucciones. Representan el resultado obtenido del procesamiento realizado."
    )


def funciones_externas():
    return (
        "Las funciones externas son funciones que ya existen en bibliotecas o módulos y pueden "
        "utilizarse dentro de un programa sin necesidad de programarlas nuevamente. Solo es "
        "necesario importar la biblioteca correspondiente."
    )


def bibliotecas():
    return (
        "Una biblioteca es un conjunto de funciones, clases y herramientas ya desarrolladas "
        "que pueden utilizarse para agregar nuevas funcionalidades a un programa. Su objetivo "
        "es facilitar el desarrollo y evitar escribir código que ya existe."
    )


def funciones_usuario():
    return (
        "Las funciones de usuario son funciones creadas por el propio programador para resolver "
        "una necesidad específica del programa. Su uso permite organizar mejor el código y "
        "reutilizar instrucciones cuando sea necesario."
    )